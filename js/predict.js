// 모델 계산 (CLAUDE.md '계산 규칙'). window.MODEL(model.js)이 먼저 로드돼 있어야 한다.
(function () {
  "use strict";
  var M = window.MODEL;
  var 하루 = 24 * 60 * 60 * 1000;

  // ---------- 날짜 ----------
  function 날짜(s) {                      // "YYYY-MM-DD" → UTC 기준 Date (시간대 영향 없음)
    var p = String(s).split("-");
    return new Date(Date.UTC(+p[0], +p[1] - 1, +p[2]));
  }
  function 날짜글(d) { return d.toISOString().slice(0, 10); }
  function 일수차(뒤, 앞) { return Math.round((날짜(뒤) - 날짜(앞)) / 하루); }
  function 더하기(s, n) { return 날짜글(new Date(날짜(s).getTime() + n * 하루)); }

  // ---------- 재료 사전 ----------
  // 입력 하나로 만들 수 있는 재료를 전부 계산해 두고, 모델의 재료 목록 순서대로 꺼낸다.
  // 목록에 모르는 이름이 있으면 멈춘다 (CLAUDE.md: 멈추고 물어본다).
  function 재료꺼내기(사전, 목록, 문제) {
    var 값 = {};
    목록.forEach(function (이름) {
      var v;
      if (이름 in 사전) v = 사전[이름];
      else if (/^유형_/.test(이름)) v = 사전.유형 === 이름.slice(3) ? 1 : 0;
      else if (/^회사_/.test(이름)) v = 사전.회사 === 이름.slice(3) ? 1 : 0;   // "그 외"면 전부 0
      else if (/^성별_/.test(이름)) v = 사전.성별 === 이름.slice(3) ? 1 : 0;
      else throw new Error(문제 + " 모델에 모르는 재료가 있음: " + 이름 + " → 입력 방식을 정해야 함");
      if (v === undefined || v === null || isNaN(v)) throw new Error(문제 + " 재료 값이 비었음: " + 이름);
      값[이름] = +v;
    });
    return 값;
  }

  // ---------- 초동: 의사결정나무 ----------
  // 입력: { 직전초동, 발매일?, 직전발매일?, 유형? }
  // 목록을 주지 않으면 '쓰는재료'만 만든다 (사이트용). 정답지 확인 때는 MODEL.초동.재료 전체를 준다.
  function 초동재료(입력, 목록) {
    var 사전 = { 직전초동: 입력.직전초동, 유형: 입력.유형 };
    if (입력.발매일) {
      사전.연도 = 날짜(입력.발매일).getUTCFullYear();
      if (입력.직전발매일) 사전.공백일 = 일수차(입력.발매일, 입력.직전발매일);
    }
    return 재료꺼내기(사전, 목록 || M.초동.쓰는재료, "초동");
  }

  function 초동확인() {
    var 다른 = M.초동.쓰는재료.filter(function (x) { return x !== "직전초동"; });
    if (다른.length) throw new Error("초동 쓰는재료에 직전초동 말고 다른 이름이 있음: " + 다른.join(", ") + " → 입력 방식을 정해야 함");
  }

  function 초동확률(재료값) {
    var 노드 = M.초동.노드, i = 0, 경로 = [];
    while (노드[i].왼쪽 !== -1) {
      var n = 노드[i], 왼쪽 = 재료값[n.재료] <= n.기준;
      경로.push({ 재료: n.재료, 기준: n.기준, 왼쪽: 왼쪽 });
      i = 왼쪽 ? n.왼쪽 : n.오른쪽;
    }
    var 확률 = 노드[i].확률.slice();
    return { 확률: 확률, 등급: 최대칸(확률), 잎: i, 앨범수: 노드[i].앨범수, 경로: 경로 };
  }

  // ---------- 시기: 로지스틱 회귀 ----------
  // 입력: { 초동, 연도 or 발매일, 공백일 or 직전발매일(없으면 데뷔작), 데뷔작?, 앨범순번, 그룹여부, 유형, 회사, 성별 }
  function 시기재료(입력) {
    var 사전 = {
      초동: 입력.초동,
      log초동: Math.log10(입력.초동),
      앨범순번: 입력.앨범순번,
      그룹여부: 입력.그룹여부,
      유형: 입력.유형, 회사: 입력.회사, 성별: 입력.성별
    };
    사전.연도 = 입력.연도 != null ? 입력.연도 : 날짜(입력.발매일).getUTCFullYear();
    if (입력.공백일 != null) {
      사전.공백일 = 입력.공백일;
      사전.데뷔작 = 입력.데뷔작 != null ? 입력.데뷔작 : 0;
    } else if (입력.직전발매일) {
      사전.공백일 = 일수차(입력.발매일, 입력.직전발매일);
      사전.데뷔작 = 0;
    } else {                                   // 데뷔작: 노트북과 같이 공백일 0
      사전.공백일 = 0;
      사전.데뷔작 = 1;
    }
    if (입력.발매일) {
      var 월 = 날짜(입력.발매일).getUTCMonth() + 1;
      사전.발매월 = 월;
      사전.월sin = Math.sin(2 * Math.PI * 월 / 12);
      사전.월cos = Math.cos(2 * Math.PI * 월 / 12);
    }
    return 재료꺼내기(사전, M.시기.재료, "시기");
  }

  function 시기확률(재료값) {
    var S = M.시기;
    var z = S.재료.map(function (이름, j) { return (재료값[이름] - S.평균[j]) / S.표준편차[j]; });
    var 점수 = S.절편.map(function (b, k) {
      var s = b;
      for (var j = 0; j < z.length; j++) s += S.계수[k][j] * z[j];
      return s;
    });
    var 확률;
    if (S.방식 === "softmax") {
      var 최대 = Math.max.apply(null, 점수);
      var e = 점수.map(function (s) { return Math.exp(s - 최대); });
      var 합 = e.reduce(function (a, b) { return a + b; }, 0);
      확률 = e.map(function (v) { return v / 합; });
    } else if (S.방식 === "ovr") {
      var sg = 점수.map(function (s) { return 1 / (1 + Math.exp(-s)); });
      var 합2 = sg.reduce(function (a, b) { return a + b; }, 0);
      확률 = sg.map(function (v) { return v / 합2; });
    } else {
      throw new Error("모르는 방식: " + S.방식);
    }
    return { 확률: 확률, 등급: 최대칸(확률) };
  }

  // 노트북 13장: 기준 발매일 + 150일까지 / +151~300일 / +301일부터
  function 시기날짜(기준발매일, 등급) {
    if (등급 === 0) return { 부터: 더하기(기준발매일, 1), 까지: 더하기(기준발매일, 150) };
    if (등급 === 1) return { 부터: 더하기(기준발매일, 151), 까지: 더하기(기준발매일, 300) };
    return { 부터: 더하기(기준발매일, 301), 까지: null };
  }

  // ---------- 사람 기준 (직전 따라가기) ----------
  function 사람초동(직전초동) {
    var b = M.초동_경계;                       // [100000, 300000], 10만 '이상'부터 다음 등급
    return 직전초동 < b[0] ? 0 : 직전초동 < b[1] ? 1 : 2;
  }
  function 사람시기(공백일, 데뷔작) {
    if (데뷔작) return M.시기.학습_최빈등급;
    var b = M.시기_경계;                       // [150, 300]
    return 공백일 <= b[0] ? 0 : 공백일 <= b[1] ? 1 : 2;
  }

  // ---------- 아티스트 한 팀 → 예측 두 개 ----------
  function 아티스트예측(a) {
    초동확인();
    var 초 = 초동확률(초동재료({ 직전초동: a.초동기준.초동 }));
    var 기 = a.시기기준;
    // 시기는 스페셜·리패키지를 빼고 계산 → 그런 앨범만 있는 팀은 시기기준이 없다 (예: 윤아, 태티서)
    if (!기) return { 초동: 초, 초동사람: 사람초동(a.초동기준.초동), 시기: null };
    var 시재 = 시기재료({
      초동: 기.초동, 연도: 기.연도, 공백일: 기.공백일, 데뷔작: 기.데뷔작, 앨범순번: 기.앨범순번,
      그룹여부: a.그룹여부, 유형: 기.유형, 회사: 기.회사 || a.회사, 성별: a.성별
    });
    var 시 = 시기확률(시재);
    return {
      초동: 초, 초동사람: 사람초동(a.초동기준.초동),
      시기: 시, 시기재료: 시재, 시기사람: 사람시기(기.공백일, 기.데뷔작),
      시기날짜: 시기날짜(기.날짜, 시.등급)
    };
  }

  // ---------- 앨범 하나 골라서 맞춰보기 (window.ALBUMS = js/albums.js) ----------
  // 팀의 i번째 앨범이 '직전 앨범'인 시점으로 돌아가서 다음 앨범을 예측하고, 실제 다음 앨범을 찾는다.
  var 본유형 = ["미니", "정규", "싱글"];
  function 앨범맞춰보기(a, i) {
    var 목록 = (window.ALBUMS || {})[a.이름] || [], x = 목록[i];
    if (!x) throw new Error("앨범 없음: " + a.이름 + " " + i);
    var 결과 = { 앨범: x, 초동: null, 시기: null, 시기이유: "", 실제: {} };

    // 초동: 고른 앨범의 초동 = 직전초동
    if (x.초동 != null) {
      초동확인();
      결과.초동 = 초동확률(초동재료({ 직전초동: x.초동 }));
      결과.초동사람 = 사람초동(x.초동);
    }
    // 실제 다음 초동: 뒤에 나온 앨범 중 초동이 있는 첫 앨범 (노트북의 직전→이번 쌍과 같은 규칙)
    for (var j = i + 1; j < 목록.length; j++) if (목록[j].초동 != null) { 결과.실제.초동 = 목록[j]; break; }

    // 시기: 본앨범(미니·정규·싱글)일 때만. 공백일 = 바로 앞 본앨범부터
    var 본 = 본유형.indexOf(x.유형) >= 0;
    var 앞 = null;
    for (var k = i - 1; k >= 0; k--) if (본유형.indexOf(목록[k].유형) >= 0) { 앞 = 목록[k]; break; }
    // (1페이지에 그대로 나가는 문구라 존댓말)
    if (!본) 결과.시기이유 = x.유형 + " 앨범은 컴백 간격 계산에서 빼기 때문에 (본앨범만 셉니다) 시기는 예측하지 않습니다.";
    else if (x.초동 == null) 결과.시기이유 = "이 앨범은 초동 기록이 없어서 시기 재료를 만들 수 없습니다.";
    else if (!앞 && x.본순번 > 1) 결과.시기이유 = "이 앨범 바로 앞 본앨범의 날짜가 목록에 없어서 공백일을 구할 수 없습니다.";
    else {
      결과.시기재료 = 시기재료({
        초동: x.초동, 발매일: x.날짜, 직전발매일: 앞 ? 앞.날짜 : null, 앨범순번: x.본순번 || 1,
        유형: x.유형, 회사: a.회사, 성별: a.성별, 그룹여부: a.그룹여부
      });
      결과.시기 = 시기확률(결과.시기재료);
      결과.시기날짜 = 시기날짜(x.날짜, 결과.시기.등급);
      결과.시기사람 = 사람시기(결과.시기재료.공백일, 결과.시기재료.데뷔작);
      결과.공백일 = 결과.시기재료.공백일;
    }
    // 실제 다음 컴백: 뒤에 나온 첫 본앨범
    for (var m = i + 1; m < 목록.length; m++) if (본유형.indexOf(목록[m].유형) >= 0) { 결과.실제.시기 = 목록[m]; break; }
    if (결과.실제.시기) {
      var 일 = 일수차(결과.실제.시기.날짜, x.날짜);
      결과.실제.일수 = 일;
      결과.실제.시기등급 = 일 <= M.시기_경계[0] ? 0 : 일 <= M.시기_경계[1] ? 1 : 2;
    }
    if (결과.실제.초동) 결과.실제.초동등급 = 사람초동(결과.실제.초동.초동);   // 실제 초동의 등급 (경계 규칙 같음)
    // 목록 뒤에 '나왔지만 확인 중'인 앨범 (사이트용_아티스트.xlsx '미반영')
    결과.실제.확인중 = ((window.ALBUMS_PENDING || {})[a.이름] || []).filter(function (p) { return p.날짜 > x.날짜; });
    return 결과;
  }

  function 최대칸(arr) {
    var k = 0;
    for (var i = 1; i < arr.length; i++) if (arr[i] > arr[k]) k = i;
    return k;
  }

  window.Predict = {
    초동재료: 초동재료, 초동확률: 초동확률, 초동확인: 초동확인,
    시기재료: 시기재료, 시기확률: 시기확률, 시기날짜: 시기날짜,
    사람초동: 사람초동, 사람시기: 사람시기,
    아티스트예측: 아티스트예측, 앨범맞춰보기: 앨범맞춰보기,
    일수차: 일수차, 더하기: 더하기
  };
})();
